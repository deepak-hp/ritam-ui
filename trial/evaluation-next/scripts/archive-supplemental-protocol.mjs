import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { root, ids, sha } from './paths.mjs';
const hash=async path=>sha(await readFile(resolve(root,path)));
const primaryBrowserHashes={};
for(const id of ids)primaryBrowserHashes[id]=await hash(`evidence/${id}/browser/browser.json`);
await mkdir(resolve(root,'evidence-supplemental'),{recursive:true});
const protocol={declaredAt:new Date().toISOString(),candidateIds:ids,verifierSha256:await hash('scripts/browser-supplemental.mjs'),helperSha256:await hash('scripts/pending-controls.mjs'),mechanicsTestSha256:await hash('scripts/pending-controls.test.mjs'),mechanicsTestResult:'pass: native/aria changing names accepted, disconnected/enabled rejected; Node 24.19.0',primaryBrowserHashes,policy:'One supplemental execution per unchanged candidate; all primary results retained.'};
await writeFile(resolve(root,'evidence-supplemental/protocol.json'),JSON.stringify(protocol,null,2),{flag:'wx'});
console.log(JSON.stringify(protocol));
