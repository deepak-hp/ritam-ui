import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
process.env.PLAYWRIGHT_BROWSERS_PATH ??= resolve('.playwright');
const { chromium } = await import('playwright');
const browser = await chromium.launch();
const base = process.env.REFERENCE_URL ?? 'http://127.0.0.1:5174';
await mkdir('.review/reference', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base);
  await page.getByRole('heading', { name: 'Projects', exact: true }).waitFor();
  const search = page.getByRole('textbox', { name: 'Search projects' });
  await search.fill('Northstar');
  await page.getByRole('button', { name: 'Website refresh', exact: true }).waitFor();
  await search.fill('there-is-no-such-project');
  await page.getByText('No projects found', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).first().click();
  await page.getByRole('button', { name: 'Website refresh', exact: true }).waitFor();
  const axeSource = await readFile('node_modules/axe-core/axe.min.js', 'utf8');
  for (const theme of ['light', 'dark']) {
    if (theme === 'dark') await page.getByRole('button', { name: 'Use dark theme' }).click();
    for (const width of [390, 1280]) {
      await page.setViewportSize({ width, height: 900 });
      await page.evaluate(() => document.fonts.ready);
      await page.screenshot({ path: `.review/reference/${theme}-${width}.png`, fullPage: true });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Page overflows ${theme}/${width}`);
    }
    await page.addScriptTag({ content: axeSource });
    const violations = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } })).violations);
    assert.deepEqual(violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), [], `Accessibility: ${theme}`);
  }
  await page.getByRole('button', { name: 'Use light theme' }).click();
  const statusFilter = page.getByRole('combobox', { name: 'Status filter', exact: true });
  await statusFilter.click();
  await page.getByRole('option', { name: 'Planning', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Website refresh', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Field notes', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).first().click();
  await page.getByRole('button', { name: /^Due dates/ }).click();
  await page.getByRole('button', { name: /September 18/ }).click();
  await page.getByRole('button', { name: /September 25/ }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Website refresh', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Harbor audit', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Clear filters', exact: true }).first().click();

  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  let editor = page.getByRole('dialog', { name: 'Create project', exact: true });
  await editor.getByRole('button', { name: 'Create project', exact: true }).click();
  const name = editor.getByRole('textbox', { name: 'Project name', exact: true });
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-invalid') === 'true');
  assert.equal(await name.getAttribute('aria-invalid'), 'true');
  await name.fill('Reference acceptance project');
  await editor.getByRole('textbox', { name: 'Client', exact: true }).fill('Acceptance Studio');
  await editor.getByRole('textbox', { name: 'Description', exact: true }).fill('A persisted project created through the public UI.');
  await editor.getByLabel('Due date', { exact: true }).fill('2026-10-16');
  await editor.getByRole('button', { name: 'Create project', exact: true }).click();
  await editor.waitFor({ state: 'hidden' });
  await search.fill('Reference acceptance');
  await page.getByRole('button', { name: 'Reference acceptance project', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('textbox', { name: 'Search projects' }).fill('Reference acceptance');
  await page.getByRole('button', { name: 'Reference acceptance project', exact: true }).waitFor();

  await page.getByRole('button', { name: 'Demo controls', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Simulate next save failure' }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Reference acceptance project', exact: true }).click();
  editor = page.getByRole('dialog', { name: 'Edit Reference acceptance project', exact: true });
  await editor.getByRole('textbox', { name: 'Project name', exact: true }).fill('Reference edited project');
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click();
  await editor.getByText('Save not complete', { exact: true }).waitFor();
  assert.equal(await editor.getByRole('textbox', { name: 'Project name', exact: true }).inputValue(), 'Reference edited project');
  const storedBeforeRetry = await page.evaluate(() => JSON.parse(localStorage.getItem('deepak-ui.reference.projects.v1')));
  assert.ok(storedBeforeRetry.projects.some(p => p.name === 'Reference acceptance project'));
  assert.ok(!storedBeforeRetry.projects.some(p => p.name === 'Reference edited project'));
  await page.addScriptTag({ content: axeSource });
  const editorViolations = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } })).violations);
  assert.deepEqual(editorViolations.map(v => v.id), [], 'Editor error accessibility');
  await page.keyboard.press('Escape');
  await editor.getByText('Discard unsaved changes?', { exact: true }).waitFor();
  await editor.getByRole('button', { name: 'Keep editing', exact: true }).click();
  assert.equal(await editor.getByRole('textbox', { name: 'Project name', exact: true }).inputValue(), 'Reference edited project');
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click();
  await editor.waitFor({ state: 'hidden' });
  await page.getByRole('textbox', { name: 'Search projects' }).fill('Reference edited');
  const edited = page.getByRole('button', { name: 'Reference edited project', exact: true });
  await edited.waitFor();
  await edited.click();
  await page.getByRole('dialog', { name: 'Edit Reference edited project', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', { name: 'Edit Reference edited project', exact: true }).waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.activeElement?.textContent === 'Reference edited project');
  await page.getByRole('button', { name: 'Demo controls', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Simulate next save failure' }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('row').filter({ has: edited }).getByRole('button', { name: 'Archive', exact: true }).click();
  const confirmation = page.getByRole('alertdialog');
  await confirmation.getByRole('button', { name: 'Archive project', exact: true }).click();
  await confirmation.getByText('Save not complete', { exact: true }).waitFor();
  await confirmation.getByRole('button', { name: 'Archive project', exact: true }).click();
  await confirmation.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'View archived projects' }).click();
  await edited.waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'View archived projects' }).click();
  await page.getByRole('textbox', { name: 'Search projects' }).fill('Reference edited');
  await edited.waitFor();

  const corruptContext = await browser.newContext();
  await corruptContext.addInitScript(() => localStorage.setItem('deepak-ui.reference.projects.v1', '{broken'));
  const corruptPage = await corruptContext.newPage();
  await corruptPage.goto(base);
  await corruptPage.getByText('Storage needs attention', { exact: true }).waitFor();
  await corruptPage.getByRole('button', { name: 'Create project', exact: true }).click();
  assert.ok(await corruptPage.getByRole('dialog', { name: 'Create project', exact: true }).getByRole('button', { name: 'Create project', exact: true }).isDisabled());
  assert.equal(await corruptPage.evaluate(() => localStorage.getItem('deepak-ui.reference.projects.v1')), '{broken');
  await corruptContext.close();
  assert.deepEqual(errors, []);
  console.log('Reference app: search/status/date filters, validation, create/reload, failed save/retry, keyboard focus, archive/reload, corrupt storage, both themes, responsive layout and axe passed.');
} finally { await browser.close(); }
