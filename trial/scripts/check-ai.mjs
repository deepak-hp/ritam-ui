import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import * as api from '../dist/index.js';
import { families } from './component-catalogue.mjs';
const contract = JSON.parse(await readFile('ai/contract.json', 'utf8'));
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
assert.equal(contract.package, pkg.name, 'AI contract package name is stale: run npm run build');
assert.equal(contract.version, pkg.version, 'AI contract package version is stale: run npm run build');
const files = (await readdir('dist')).filter(f => f.endsWith('.d.ts')).sort();
const declarations = Object.fromEntries(await Promise.all(files.map(async f => [f, await readFile(`dist/${f}`, 'utf8')])));
const tokens = await readFile('src/tokens.css', 'utf8');
const guide = await readFile('ai/README.md', 'utf8');
const composition = await readFile('ai/COMPOSITION.md', 'utf8');
assert.equal(contract.fingerprint, createHash('sha256').update(JSON.stringify({ declarations, tokens, guide, composition })).digest('hex'), 'AI contract is stale: run npm run build');
assert.deepEqual([...contract.components, ...contract.hooks].sort(), Object.keys(api).sort(), 'AI index must cover exactly the public runtime exports');
assert.deepEqual(contract.families, families, 'AI component families are stale');
const text = await readFile('ai/llms-full.txt', 'utf8');
for (const declaration of Object.values(declarations)) assert.ok(text.includes(declaration), 'Missing API declaration in full text');
assert.ok(text.includes(tokens), 'Missing tokens');
assert.ok(text.includes(composition), 'Missing composition guidance');
assert.equal(await readFile('docs/agent-api.generated.md', 'utf8'), text, 'Storybook API mirror is stale');
assert.equal(await readFile('docs/ai-integration.generated.md', 'utf8'), guide, 'Storybook integration mirror is stale');
assert.equal(await readFile('docs/composition.generated.md', 'utf8'), composition, 'Storybook composition mirror is stale');
console.log(`AI contract verified: ${contract.components.length} components, ${contract.hooks.length} hook, current declarations and tokens.`);
